# 1. Initialize our local LLM engine (Qwen2.5:3b)
# temperature=0 kuduthurukkom, so that strict ah factual ah answer pannum.
llm = ChatOllama(model="qwen2.5:3b", temperature=0)

# 2. Define the exact structure we want from the Router
class RouterOutput(BaseModel):
    sub_tasks: List[str] = Field(description="List of step-by-step tasks to research the user's query")

# 3. Create the Router Agent Node (Function)
def router_node(state: GraphState):
    print("--- 🧠 ROUTER AGENT: Thinking ---")
    query = state["user_query"]
    
    # Prompting the LLM to act as a manager
    prompt = f"You are a research manager. Break down this complex query into 2 or 3 specific research tasks: {query}"
    
    # Force the LLM to reply strictly in our RouterOutput list format
    structured_llm = llm.with_structured_output(RouterOutput)
    response = structured_llm.invoke(prompt)
    
    # Update the shared note-book (state) with the new tasks
    return {"sub_tasks": response.sub_tasks}
