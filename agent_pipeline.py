from langchain_text_splitters import RecursiveCharacterTextSplitter
from langchain_chroma import Chroma
from langchain_ollama import OllamaEmbeddings

# Initialize the embedding model we downloaded (nomic-embed-text)
embeddings = OllamaEmbeddings(model="nomic-embed-text")

# --- DATABASE SETUP FUNCTION ---
def setup_vector_database(pdf_path: str):
    """Loads a PDF, chunks it, and saves it to a local Chroma database."""
    print(f"--- 📚 LOADING DOCUMENT: {pdf_path} ---")
    
    # 1. Load the PDF
    loader = PyPDFLoader(pdf_path)
    docs = loader.load()
    
    # 2. Split into chunks for Parent-Document Retrieval
    text_splitter = RecursiveCharacterTextSplitter(chunk_size=1000, chunk_overlap=200)
    splits = text_splitter.split_documents(docs)
    
    # 3. Store in local ChromaDB
    print("--- 🗄️ STORING IN CHROMADB ---")
    vectorstore = Chroma.from_documents(
        documents=splits, 
        embedding=embeddings, 
        persist_directory="./chroma_db"
    )
    return vectorstore

# --- AGENT 2: RAG SPECIALIST ---
def rag_node(state: GraphState):
    """Searches the database using the sub-tasks generated by the Router."""
    print("--- 🔎 RAG SPECIALIST: Searching Database ---")
    
    # Connect to the existing local database
    vectorstore = Chroma(persist_directory="./chroma_db", embedding_function=embeddings)
    
    # Set the retriever to fetch the top 2 most relevant chunks
    retriever = vectorstore.as_retriever(search_kwargs={"k": 2})
    
    # Get the first sub-task created by the Router to use as the search query
    search_query = state["sub_tasks"][0]
    print(f"Executing Search Query: {search_query[:50]}...")
    
    # Fetch matching documents
    docs = retriever.invoke(search_query)
    
    # Format the results into our GraphState structure
    retrieved_data = []
    for doc in docs:
        retrieved_data.append(
            RetrievedDocument(
                content=doc.page_content, 
                source_file=doc.metadata.get("source", "Unknown")
            )
        )
        
    # Update the shared state notebook
    return {"retrieved_docs": retrieved_data}